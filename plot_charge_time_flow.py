def build_commodity_graph(x_load, x_ener):
    lf, ef = defaultdict(float), defaultdict(float)
    for (n1, n2, _), flow in x_load.items():
        if flow >= 0.05: lf[(n1[:3], n2[:3])] += flow
    for (n1, n2, _), flow in x_ener.items():
        if flow >= 0.05: ef[(n1[:3], n2[:3])] += flow
    Gk = nx.DiGraph()
    for (u, v), flow in lf.items():
        Gk.add_edge(u, v, load=flow, ener=ef.get((u, v), 0))
    for (u, v), flow in ef.items():
        if (u, v) not in lf:
            Gk.add_edge(u, v, load=0, ener=flow)
    return Gk, lf

def flow_x_rank(x_load):
    """BFS depth from sources in x_load spatial graph → x-axis rank."""
    sp = nx.DiGraph()
    for (n1, n2, _), flow in x_load.items():
        if flow >= 0.05 and n1[0] != n2[0]:
            i, j = n1[0], n2[0]
            sp.add_edge(i, j, weight=sp[i][j]['weight'] + flow
                        if sp.has_edge(i, j) else flow)
    sources = [i for i in sp.nodes if sp.in_degree(i) == 0]
    depth = {s: 0 for s in sources}
    queue = list(sources)
    while queue:
        curr = queue.pop(0)
        for _, nxt in sp.out_edges(curr):
            if nxt not in depth:
                depth[nxt] = depth[curr] + 1
                queue.append(nxt)
    all_sp = sorted(set(sp.nodes))
    max_d = max(depth.values(), default=0)
    for i in all_sp:
        if i not in depth:
            depth[i] = max_d + 1
    ordered = sorted(all_sp, key=lambda i: (depth[i], i))
    return {i: r for r, i in enumerate(ordered)}, ordered

