if NROWS == 1: axes = [axes]

fig.suptitle('ChargeTimeNetwork flow subgraph\n'
             'Rows = time ranges  |  Cols = commodities  |  '
             'x = node (flow direction →)  |  y = charge (%)',
             fontsize=11, y=1.01)

legend_items = [
    Line2D([0],[0], color='#2166AC', lw=2.5, label='x_load (loaded)'),
    Line2D([0],[0], color='#CC3333', lw=2.5, alpha=0.5, label='x_ener'),
    mpatches.Patch(facecolor=CITY_COLOR[28], label='LA (28)'),
    mpatches.Patch(facecolor=CITY_COLOR[13], label='PHX (13)'),
    mpatches.Patch(facecolor=CITY_COLOR[49], label='DAL (49)'),
    Line2D([0],[0], marker='*', color='w', markerfacecolor='gold',
           markeredgecolor='black', markersize=9, label='n[i]>0'),
]

for row_idx, (t_lo, t_hi) in enumerate(active_ranges):
    for col_idx, (Gk, rank_k, ordered_k, label) in enumerate(commodity_data):
        ax = axes[row_idx][col_idx]

        panel_nodes = nodes_in_range(Gk, t_lo, t_hi)
        panel_set   = set(panel_nodes)

        def kpos(n):
            return rank_k.get(n[0], len(ordered_k)), n[1]

        # Edges
        curve_count = defaultdict(int)
        for u, v, d in Gk.edges(data=True):
            if u not in panel_set:
                continue
            x1, y1 = kpos(u)
            x2, y2 = kpos(v)
            ep = (round(x1,2), round(y1,1), round(x2,2), round(y2,1))
            for flow, color, alpha, zo in [
                (d['ener'], '#CC3333', 0.35, 2),
                (d['load'], '#2166AC', 0.88, 3),
            ]:
                if flow <= 0: continue
                lw = 0.5 + 3.5 * (flow / max_flow)
                curve_count[ep] += 1
                same = abs(x1-x2) < 0.1 and abs(y1-y2) < 1
                rad  = (0.3 + 0.15 * curve_count[ep]) if same else 0.0
                ax.annotate('', xy=(x2, y2), xytext=(x1, y1),
                    arrowprops=dict(
                        arrowstyle=f'-|>,head_width={max(0.15,lw*0.1)},head_length=0.4',
                        color=color, lw=lw, alpha=alpha,
                        connectionstyle=f'arc3,rad={rad}'),
                    zorder=zo)

        # Nodes
        seen = set()
        for n in panel_nodes:
            i, g, t = n
            x, y = kpos(n)
            nc = CITY_COLOR.get(i, charge_cmap(charge_norm(g)))
            ms = 70 if i in CITY_LABEL else 20
            ax.scatter(x, y, s=ms, color=nc, edgecolors='black',
                       linewidths=0.6 if i in CITY_LABEL else 0.2, zorder=5)
            ax.annotate(f'({i},{g},{t})', (x, y), xytext=(2, 2),
                        textcoords='offset points',
                        fontsize=3.5, ha='left', va='bottom', color='black')
            if i in n_vals and i not in seen:
                ax.scatter(x, y, s=ms*5, marker='*', color='gold',
                           edgecolors='black', linewidths=0.4, zorder=7, alpha=0.9)
            seen.add(i)

        x_hi = len(ordered_k) - 0.5
        ax.set_xlim(-0.5, x_hi)
        ax.set_ylim(-5, 112)
        ax.set_xticks(range(len(ordered_k)))
        ax.set_xticklabels([str(i) for i in ordered_k], fontsize=4, rotation=90)
        ax.axhline(0,   color='#cccccc', lw=0.5, ls=':', zorder=0)
        ax.axhline(100, color='#88cc88', lw=0.5, ls=':', zorder=0)
        ax.grid(True, alpha=0.12, axis='x', zorder=0)
        ax.tick_params(axis='y', labelsize=6)

        if row_idx == 0:
            ax.set_title(label, fontsize=9, fontweight='bold')
        if col_idx == 0:
            ax.set_ylabel(f't∈[{t_lo},{t_hi}]\nCharge(%)', fontsize=7)
        if row_idx == n_time - 1:
            ax.set_xlabel('Node (flow direction →)', fontsize=7)
        if row_idx == 0 and col_idx == 0:
            ax.legend(handles=legend_items, loc='upper left', fontsize=5.5)

